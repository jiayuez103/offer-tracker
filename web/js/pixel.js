/**
 * 把一组格子画成路径：同一行连续的格子合成一条；上下相邻的同色格子之间再垫一条横跨两行的，
 * 这样图标缩放到非整数倍（比如 12px）时，行与行之间不会露出细缝。
 * at(y, x) 返回这个格子要不要画。
 */
export function cellsToPath(at, width, height, offsetX = 0) {
  let d = '';
  const run = (y, test, top) => {
    for (let x = 0; x < width;) {
      if (!test(x)) { x += 1; continue; }
      let end = x;
      while (end < width && test(end)) end += 1;
      d += `M${offsetX + x} ${top}h${end - x}v1h${x - end}z`;
      x = end;
    }
  };
  for (let y = 0; y < height; y += 1) {
    run(y, (x) => at(y, x), y);
    if (y + 1 < height) run(y, (x) => at(y, x) && at(y + 1, x), y + 0.5);
  }
  return d;
}

const iconCache = new Map();

/** 图标的内联 SVG 字符串；名字不认识就返回空串 */
export function iconSvg(name) {
  const key = ICONS[name] ? name : ICON_ALIAS[name];
  const rows = ICONS[key];
  if (!rows) return '';
  if (!iconCache.has(key)) {
    const cell = (y, x) => (y >= 0 && y < 16 && x >= 0 && x < 16 ? rows[y][x] : '.');
    // 先画色块、最后画描边；色块往相邻的后画颜色底下多铺一格，缩放时描边和色块之间不会透出底色
    const order = [...new Set(rows.join(''))].filter((c) => c !== '.').sort((a, b) => (a === '#') - (b === '#'));
    const rank = Object.fromEntries(order.map((c, i) => [c, i]));
    const body = order.map((c, i) => {
      const at = (y, x) => {
        const ch = cell(y, x);
        if (ch === c) return true;
        if (ch === '.' || rank[ch] <= i) return false;
        return cell(y - 1, x) === c || cell(y + 1, x) === c || cell(y, x - 1) === c || cell(y, x + 1) === c;
      };
      return `<path class="px-${c === '#' ? 'ink' : c}" d="${cellsToPath(at, 16, 16)}"/>`;
    }).join('');
    iconCache.set(key, `<svg viewBox="0 0 16 16" aria-hidden="true" focusable="false">${body}</svg>`);
  }
  return iconCache.get(key);
}

/** 像素字的 SVG 字符串和宽高比；不认识的字符留一个空位 */
export function pixelTextSvg(text) {
  let x = 0;
  let d = '';
  for (const ch of String(text)) {
    const glyph = GLYPHS[ch];
    if (!glyph) { x += 3; continue; }
    const width = glyph[0].length;
    d += cellsToPath((gy, gx) => (glyph[gy] ? glyph[gy][gx] === '#' : false), width, 7, x);
    x += width + 1;
  }
  const width = Math.max(1, x - 1);
  return { width, svg: `<svg viewBox="0 0 ${width} 7" aria-hidden="true" focusable="false"><path d="${d}" fill="currentColor"/></svg>` };
}

/** 像素字元素（数字卡片、logo 用）。height 是显示高度（px），读屏软件读到的是原文字 */
export function pixelText(text, height = 28) {
  const { width, svg } = pixelTextSvg(text);
  const span = document.createElement('span');
  span.className = 'px-text';
  span.setAttribute('role', 'img');
  span.setAttribute('aria-label', String(text));
  span.style.width = `${Math.round((height * width) / 7)}px`;
  span.style.height = `${height}px`;
  span.innerHTML = svg;
  return span;
}
